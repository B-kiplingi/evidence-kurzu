-- V2: Rozšíření schématu o termíny, lektory, dny výuky, přihlášky s pořadníkem, docházku a osvědčení

ALTER TABLE users ADD COLUMN phone VARCHAR(30);

CREATE TABLE IF NOT EXISTS course_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    location VARCHAR(150) NOT NULL,
    capacity INT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PLANNED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_course_terms_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS term_lecturers (
    term_id BIGINT NOT NULL,
    lecturer_id BIGINT NOT NULL,
    PRIMARY KEY (term_id, lecturer_id),
    CONSTRAINT fk_term_lecturers_term FOREIGN KEY (term_id) REFERENCES course_terms(id) ON DELETE CASCADE,
    CONSTRAINT fk_term_lecturers_lecturer FOREIGN KEY (lecturer_id) REFERENCES users(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS term_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id BIGINT NOT NULL,
    day_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    hours_count INT NOT NULL,
    lecturer_id BIGINT,
    topic VARCHAR(255),
    CONSTRAINT fk_term_days_term FOREIGN KEY (term_id) REFERENCES course_terms(id) ON DELETE CASCADE,
    CONSTRAINT fk_term_days_lecturer FOREIGN KEY (lecturer_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    queue_position INT,
    exception_reason VARCHAR(255),
    cancellation_reason VARCHAR(255),
    cancelled_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_registrations_term FOREIGN KEY (term_id) REFERENCES course_terms(id) ON DELETE RESTRICT,
    CONSTRAINT fk_registrations_student FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS attendances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_day_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    is_present BOOLEAN NOT NULL DEFAULT FALSE,
    note VARCHAR(255),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_attendances_day FOREIGN KEY (term_day_id) REFERENCES term_days(id) ON DELETE CASCADE,
    CONSTRAINT fk_attendances_reg FOREIGN KEY (registration_id) REFERENCES registrations(id) ON DELETE CASCADE,
    CONSTRAINT uq_attendance UNIQUE (term_day_id, registration_id)
);

CREATE TABLE IF NOT EXISTS certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL UNIQUE,
    certificate_number VARCHAR(50) NOT NULL UNIQUE,
    issue_date DATE NOT NULL,
    student_name VARCHAR(150) NOT NULL,
    course_name VARCHAR(150) NOT NULL,
    hours_duration INT NOT NULL,
    is_accredited BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_certificates_reg FOREIGN KEY (registration_id) REFERENCES registrations(id) ON DELETE RESTRICT
);
